import { writeFile } from "node:fs/promises";

// Regenerates app/alert-colors.ts — the colour NWS itself paints each alert type:
//
//   node scripts/build-alert-colors.mjs
//
// Read from the `drawingInfo` renderer on the event-driven watch/warning service, for the
// same reason the SPC and WPC palettes are read from theirs: these colours are the public's
// reference for what a hazard looks like, and eyeballing a hex puts a Tornado Warning in
// nearly-but-not-quite the red everyone recognises.
//
// The renderer keys on `prod_type`, which is the same string the alerts API returns as
// `event`, so the table joins directly with no mapping in between.

const SERVICE = "https://mapservices.weather.noaa.gov/eventdriven/rest/services/WWA/watch_warn_adv/MapServer/1";

const hex = (color) =>
  `#${color.slice(0, 3).map((channel) => channel.toString(16).padStart(2, "0")).join("")}`;

const response = await fetch(`${SERVICE}?f=json`, { signal: AbortSignal.timeout(120_000) });
if (!response.ok) throw new Error(`watch/warning renderer: ${response.status}`);
const renderer = (await response.json()).drawingInfo?.renderer;
if (renderer?.type !== "uniqueValue") throw new Error(`unexpected renderer: ${renderer?.type}`);

const entries = renderer.uniqueValueInfos
  .filter((info) => info.value && info.symbol?.color)
  .map((info) => [
    info.value,
    { fill: hex(info.symbol.color), stroke: hex(info.symbol.outline?.color ?? info.symbol.color) },
  ])
  .sort(([a], [b]) => a.localeCompare(b));
if (entries.length < 80) throw new Error(`only ${entries.length} alert colours — the renderer shape probably changed`);

const body = entries
  .map(([event, { fill, stroke }]) => `  ${JSON.stringify(event)}: { fill: "${fill}", stroke: "${stroke}" },`)
  .join("\n");

await writeFile(
  new URL("../app/alert-colors.ts", import.meta.url),
  `// Generated by scripts/build-alert-colors.mjs from the NWS watch/warning renderer.
// Do not edit by hand — re-run the script instead.
//
// Keyed by the alerts API's \`event\` string (the service's \`prod_type\`), so a lookup is a
// direct hit with no normalisation. ${entries.length} event types.

export type AlertColor = { fill: string; stroke: string };

export const ALERT_COLORS: Record<string, AlertColor> = {
${body}
};

/**
 * Used when NWS ships an event this table doesn't carry. Deliberately a flat grey rather
 * than a guessed hazard colour: an unknown alert reading as "some alert" is honest, while
 * one painted red or yellow claims a severity nobody assigned it.
 */
export const DEFAULT_ALERT_COLOR: AlertColor = { fill: "#9ca3af", stroke: "#4b5563" };
`,
);

console.log(`app/alert-colors.ts: ${entries.length} event colours`);
