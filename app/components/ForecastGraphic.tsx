/**
 * Everything both product kinds share: an offscreen 2× canvas, basemap tiles, and the
 * graticule, clipped to the plot. Returns the pieces each renderer needs to draw on top.
 */
async function beginMapCanvas(bundle: OfficeBundle) {
  const width = PLOT_WIDTH;
  const height = MAP_HEIGHT;
  const mapCanvas = document.createElement("canvas");
  mapCanvas.width = width * RENDER_SCALE;
  mapCanvas.height = height * RENDER_SCALE;
  const context = mapCanvas.getContext("2d")!;
  context.setTransform(RENDER_SCALE, 0, 0, RENDER_SCALE, 0, 0);
  context.lineJoin = "round";
  context.imageSmoothingEnabled = true;
  context.imageSmoothingQuality = "high";
  if (document.fonts?.ready) await document.fonts.ready;

  // Work in logical pixels while the backing canvas renders at 2× resolution.
  const plot = { x: 0, y: 0, width, height };
  context.fillStyle = "#dfe8ee";
  context.fillRect(plot.x, plot.y, plot.width, plot.height);
  const bounds = bundle.bounds;
  // The office's own tile zoom, not a global one: `plotExtent` stretches any extent to
  // fill the canvas, so zoom decides only which basemap tiles are fetched. Held at a
  // single level, the 78 smallest offices upscale one tile across the whole map and the
  // largest pulls thousands it immediately throws away.
  const extent = plotExtent(bounds, plot.width, plot.height, bundle.zoom);
  const shiftLongitude = longitudeShiftFor(bounds);
  const projectPoint = (lon: number, lat: number) => project(shiftLongitude(lon), lat, extent, plot.x, plot.y, plot.width, plot.height);
  await drawTiles(context, extent, plot.x, plot.y, plot.width);

  context.save();
  context.beginPath();
  context.rect(plot.x, plot.y, plot.width, plot.height);
  context.clip();

  context.strokeStyle = "#64748b40";
  context.lineWidth = 0.8;
  context.setLineDash([2, 4]);
  // A fixed 0.5° step suits a 2.5°-wide office and turns a 46°-wide one into 93 lines of
  // noise, so the step grows with the frame to keep roughly the same number of gridlines.
  const step = GRATICULE_STEPS.find((candidate) => (bounds.east - bounds.west) / candidate <= 12) ?? GRATICULE_STEPS.at(-1)!;
  for (let lon = Math.ceil(bounds.west / step) * step; lon <= bounds.east; lon += step) {
    const a = project(lon, bounds.south - step, extent, plot.x, plot.y, plot.width, plot.height);
    const b = project(lon, bounds.north + step, extent, plot.x, plot.y, plot.width, plot.height);
    context.beginPath(); context.moveTo(...a); context.lineTo(...b); context.stroke();
  }
  for (let lat = Math.ceil(bounds.south / step) * step; lat <= bounds.north; lat += step) {
    const a = project(bounds.west - step * 2, lat, extent, plot.x, plot.y, plot.width, plot.height);
    const b = project(bounds.east + step * 2, lat, extent, plot.x, plot.y, plot.width, plot.height);
    context.beginPath(); context.moveTo(...a); context.lineTo(...b); context.stroke();
  }
  context.setLineDash([]);

  return { mapCanvas, context, plot, bounds, extent, projectPoint, width, height };
}

