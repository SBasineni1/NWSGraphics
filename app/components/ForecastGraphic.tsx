/**
 * An office whose area crosses the antimeridian carries `bounds.east` past 180, and every
 * coordinate in its bundle is shifted to match. Forecast points come from the NWS API in
 * ordinary -180..180 terms, so they have to be shifted into the same space before being
 * projected — otherwise an Aleutian gridpoint lands a whole world away from the map it
 * belongs to.
 */
/** Graticule spacings in degrees, coarsest chosen that keeps the frame under ~12 lines. */
const GRATICULE_STEPS = [0.5, 1, 2, 5, 10];

function longitudeShiftFor(bounds: Bounds) {
  if (bounds.east <= 180) return (lon: number) => lon;
  return (lon: number) => (lon < 0 ? lon + 360 : lon);
}

// The NWS source ships some CWAs as Polygon and others as MultiPolygon, so normalize.
function traceAreas(context: CanvasRenderingContext2D, areas: AreaGeometry[], projectPoint: (lon: number, lat: number) => [number, number]) {
  context.beginPath();
  for (const geometry of areas) {
    const polygons = geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
    for (const polygon of polygons) {
      for (const ring of polygon) {
        ring.forEach((position, index) => {
          const [x, y] = projectPoint(position[0], position[1]);
          if (index === 0) context.moveTo(x, y); else context.lineTo(x, y);
        });
        context.closePath();
      }
    }
  }
}

function traceLines(context: CanvasRenderingContext2D, lines: LineGeometry[], projectPoint: (lon: number, lat: number) => [number, number]) {
  context.beginPath();
  for (const feature of lines) {
    const parts = feature.type === "LineString" ? [feature.coordinates] : feature.coordinates;
    for (const part of parts) {
      part.forEach((position, index) => {
        const [x, y] = projectPoint(position[0], position[1]);
        if (index === 0) context.moveTo(x, y); else context.lineTo(x, y);
      });
    }
  }
}

function hexToRgb(hex: string) {
  return [Number.parseInt(hex.slice(1, 3), 16), Number.parseInt(hex.slice(3, 5), 16), Number.parseInt(hex.slice(5, 7), 16)];
}

/**
 * The colour for a value on a **field** product — interpolated between the two stops it
 * falls between.
 *
 * Field products are continuous measurements and blend; the categorical products do not,
 * and they are a different code path entirely (SPC/WPC outlooks carry the issuing centre's
 * own discrete fills, and alerts paint flat `ALERT_COLORS` on their own layer). Don't
 * unify the two.
 *
 * Banding the field was tried and reverted: the stops are 10° apart on the temperature
 * scales, so a real day spanning 78–90°F collapsed into two flat blocks and the map lost
 * every gradient that made it readable. The legend's flat per-stop swatches are a key to
 * the scale, not a claim that the field is quantised.
 */
function colorFor(value: number, stops: ColorStop[]) {
  if (value <= stops[0].value) return hexToRgb(stops[0].color);
  if (value >= stops.at(-1)!.value) return hexToRgb(stops.at(-1)!.color);
  const upperIndex = stops.findIndex((stop) => value <= stop.value);
  const lower = stops[upperIndex - 1];
  const upper = stops[upperIndex];
  const amount = (value - lower.value) / (upper.value - lower.value);
  const a = hexToRgb(lower.color);
  const b = hexToRgb(upper.color);
  return a.map((channel, index) => Math.round(channel + (b[index] - channel) * amount));
}

// `colorFor` re-parses hex strings on every call, which is far too slow to run once per
// pixel. Bake it into a ramp instead. The stops are not evenly spaced (QPF runs 0, 0.01,
// 0.1, 0.25, 0.5, 1, 2, 3, 4, 5, 6, 8, 10, 12), so each entry has to come from `colorFor`
// itself rather than from walking between stops at uniform intervals.
const colorRamps = new WeakMap<ColorStop[], { table: Uint8ClampedArray; min: number; span: number }>();

function colorRamp(stops: ColorStop[]) {
  const cached = colorRamps.get(stops);
  if (cached) return cached;
  const min = stops[0].value;
  const span = stops.at(-1)!.value - min;
  const table = new Uint8ClampedArray(COLOR_LUT_SIZE * 3);
  for (let index = 0; index < COLOR_LUT_SIZE; index += 1) {
    const [red, green, blue] = colorFor(min + span * (index / (COLOR_LUT_SIZE - 1)), stops);
    table[index * 3] = red;
    table[index * 3 + 1] = green;
    table[index * 3 + 2] = blue;
  }
  const ramp = { table, min, span };
  colorRamps.set(stops, ramp);
  return ramp;
}

/**
 * The inverse-distance solve, precomputed.
 *
 * Which eight points are nearest a lattice cell, and how much each is weighted, depends
 * only on where the points and the cell *are* — not on which product or day is being
 * drawn. The office renders forty plots over one lattice and one set of gridpoints, so
 * solving it per plot repeats the same 8-nearest search forty times: it was the single
 * largest cost in a render, ahead of everything else the profile showed.
 *
 * So the search runs once and the result is reused. Each plot is then a weighted sum
 * over eight already-chosen neighbours, which is arithmetic rather than a scan of every
 * point in the region.
 *
 * The key has to include the point set, not just the office: a product where some
 * gridpoints report null is a genuinely different set, with different nearest
 * neighbours, and reusing another product's solve for it would silently move values
 * around the map.
 */
// Weights are float64, not float32: the per-plot sum has to stay bit-for-bit what the
// per-pixel solve produced, or the ramp lookup can land a pixel in the neighbouring
// colour band and the optimisation would show up as a changed map.
type FieldSolve = { indices: Int32Array; weights: Float64Array; exact: Int32Array; support: Float32Array };
const NEIGHBOR_COUNT = 8;
/**
 * Shepard smoothing, as a fraction of the lattice's own spacing.
 *
 * Inverse-distance weighting goes singular at a data point — the weight blows up and the
 * cell takes that point's value outright — so a coarse lattice renders as one bullseye per
 * gridpoint. A smoothing term in the denominator caps that. It has to scale with spacing:
 * this was a hard-coded 0.0005, which is exactly (0.1 × 0.219°)², PHI's spacing. At
 * national scale the spacing is ~1.7°, where that constant is 58× too small and every
 * gridpoint shows as a blob. Expressed as a ratio it reproduces the old value for a CWA
 * frame and widens correctly for the national one.
 */
const SHEPARD_SMOOTHING = 0.35;
/**
 * How far from real data a cell may sit, in multiples of lattice spacing, before the field
 * fades out. A CWA lattice covers its whole frame, so this never fires there — that is why
 * the old blanket coverage mask was removed. The national frame is different: it reaches
 * far into the Atlantic, Pacific and Gulf where NWS publishes no gridded forecast at all,
 * and without a fade the raster extrapolates land values hundreds of miles offshore.
 */
const SUPPORT_FULL = 1.6;
const SUPPORT_NONE = 3.2;

function solveFieldWeights(points: ForecastPoint[], columns: number, rows: number, positionOf: (column: number, row: number) => { lon: number; lat: number }): FieldSolve {
  const cells = columns * rows;
  const indices = new Int32Array(cells * NEIGHBOR_COUNT).fill(-1);
  const weights = new Float64Array(cells * NEIGHBOR_COUNT);
  // A cell sitting exactly on a gridpoint takes that point's value outright, the same
  // short-circuit the per-pixel solve had.
  const exact = new Int32Array(cells).fill(-1);
  // Distance to the nearest contributing point, in multiples of lattice spacing.
  const support = new Float32Array(cells);
  const near: Array<{ distanceSquared: number; index: number }> = [];

  // Characteristic spacing of this lattice: the frame's area shared between its points.
  // Latitude-scaled to match the distance metric used below, so it is comparable across a
  // 2.5° office frame and a 59° national one.
  const first = positionOf(0, 0);
  const last = positionOf(columns - 1, rows - 1);
  const midLatitude = (first.lat + last.lat) / 2;
  const width = Math.abs(last.lon - first.lon) * Math.cos(midLatitude * Math.PI / 180);
  const height = Math.abs(last.lat - first.lat);
  const spacing = Math.sqrt(Math.max(width * height, 1e-9) / Math.max(points.length, 1));
  const smoothing = (SHEPARD_SMOOTHING * spacing) ** 2;
  for (let row = 0; row < rows; row += 1) {
    for (let column = 0; column < columns; column += 1) {
      const cell = row * columns + column;
      const { lon, lat } = positionOf(column, row);
      const scale = Math.cos(lat * Math.PI / 180);
      near.length = 0;
      for (let index = 0; index < points.length; index += 1) {
        const point = points[index];
        const dx = (lon - point.lon) * scale;
        const dy = lat - point.lat;
        const distanceSquared = dx * dx + dy * dy;
        if (distanceSquared < 0.000001) {
          exact[cell] = index;
          break;
        }
        const insertAt = near.findIndex((neighbor) => distanceSquared < neighbor.distanceSquared);
        if (insertAt === -1) {
          if (near.length < NEIGHBOR_COUNT) near.push({ distanceSquared, index });
        } else {
          near.splice(insertAt, 0, { distanceSquared, index });
          if (near.length > NEIGHBOR_COUNT) near.pop();
        }
      }
      if (exact[cell] !== -1) {
        support[cell] = 0;
        continue;
      }
      support[cell] = near.length ? Math.sqrt(near[0].distanceSquared) / spacing : Infinity;
      for (let slot = 0; slot < near.length; slot += 1) {
        indices[cell * NEIGHBOR_COUNT + slot] = near[slot].index;
        weights[cell * NEIGHBOR_COUNT + slot] = 1 / Math.pow(near[slot].distanceSquared + smoothing, 1.35);
      }
    }
  }
  return { indices, weights, exact, support };
}

// Cleared whenever the lattice geometry changes, so a solve can never outlive the frame
// it was computed for.
let fieldSolveCache = new Map<string, FieldSolve>();
let fieldSolveFrame = "";

function fieldSolveFor(points: ForecastPoint[], frame: string, columns: number, rows: number, positionOf: (column: number, row: number) => { lon: number; lat: number }) {
  if (fieldSolveFrame !== frame) {
    fieldSolveCache = new Map();
    fieldSolveFrame = frame;
  }
  // Identifies the exact set of contributing points, in order.
  const key = points.map((point) => point.id).join("|");
  const cached = fieldSolveCache.get(key);
  if (cached) return cached;
  const solve = solveFieldWeights(points, columns, rows, positionOf);
  fieldSolveCache.set(key, solve);
  return solve;
}

// Every canvas at a given extent shares these promises, so a basemap request that hangs
// would stall the whole page rather than one tile: `drawTiles` awaits them all, the
// render never resolves, and the publisher's readiness wait times out. Two guards —
// a hard timeout, and eviction on failure so a hung request is never cached and reused.
const TILE_TIMEOUT_MS = 15_000;

function loadTile(url: string) {
  const cached = tileCache.get(url);
  if (cached) return cached;
  const request = fetch(url, { signal: AbortSignal.timeout(TILE_TIMEOUT_MS) })
    .then(async (response) => {
      if (!response.ok) throw new Error("Basemap unavailable");
      return createImageBitmap(await response.blob());
    });
  request.catch(() => tileCache.delete(url));
  tileCache.set(url, request);
  return request;
}

async function drawTiles(context: CanvasRenderingContext2D, extent: MapExtent, x: number, y: number, width: number) {
  const firstX = Math.floor(extent.left / 256);
  const lastX = Math.floor(extent.right / 256);
  const firstY = Math.floor(extent.top / 256);
  const lastY = Math.floor(extent.bottom / 256);
  const scale = width / (extent.right - extent.left);
  await Promise.all(Array.from({ length: lastX - firstX + 1 }, (_, xi) => firstX + xi).flatMap((tileX) =>
    Array.from({ length: lastY - firstY + 1 }, (_, yi) => firstY + yi).map(async (tileY) => {
      try {
        const url = `https://a.basemaps.cartocdn.com/rastertiles/voyager_nolabels/${extent.zoom}/${tileX}/${tileY}@2x.png`;
        const bitmap = await loadTile(url);
        context.drawImage(bitmap, x + (tileX * 256 - extent.left) * scale, y + (tileY * 256 - extent.top) * scale, 256 * scale, 256 * scale);
      } catch {
        // The forecast remains usable over the neutral fallback background.
      }
    }),
  ));
}

