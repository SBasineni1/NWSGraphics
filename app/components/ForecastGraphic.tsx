// The `?office=` parameter is the single source of truth for the selection, so deep
// links, the publisher's per-office navigation, and browser back/forward all agree.
// `replaceState` doesn't fire `popstate`, hence the companion event.
const OFFICE_CHANGE_EVENT = "forecast-office-change";

function subscribeToOfficeParam(onChange: () => void) {
  window.addEventListener("popstate", onChange);
  window.addEventListener(OFFICE_CHANGE_EVENT, onChange);
  return () => {
    window.removeEventListener("popstate", onChange);
    window.removeEventListener(OFFICE_CHANGE_EVENT, onChange);
  };
}

function readOfficeParam(): string {
  return new URLSearchParams(window.location.search).get("office") ?? DEFAULT_OFFICE;
}

function writeOfficeParam(id: OfficeId) {
  const url = new URL(window.location.href);
  url.searchParams.set("office", id);
  window.history.replaceState(null, "", url);
  window.dispatchEvent(new Event(OFFICE_CHANGE_EVENT));
}

// Exit is deliberately quicker than entry and not staggered — a cascade on the way out
// reads as lag. Must stay in step with the office-menu-out duration in globals.css.
const MENU_EXIT_MS = 130;

// Search resolves a town or ZIP to an office *id*; the picker needs the office itself, to
// know whether it is drawable. Unlike `findOffice`, a miss here is null rather than the
// default office — search saying "we found nothing" has to be distinguishable from search
// saying "we found PHI".
const OFFICE_BY_ID = new Map(OFFICES.map((office) => [office.id, office]));

type PlaceIndex = ReturnType<typeof parsePlaceIndex>;
type IndexState = "idle" | "loading" | "ready" | "error";

/**
 * The place index is ~280 KB over the wire — every US town and ZIP — so it is fetched on
 * the first sign of intent to search rather than with the page or even with the menu.
 * Most visits never open it, and someone who opens the picker to browse regions should
 * not pay for a search they aren't doing.
 */
type LocateState = "idle" | "locating" | "denied" | "unavailable" | "unsupported";

/**
 * The office that forecasts a coordinate, straight from NWS.
 *
 * `properties.cwa` is the authority, not a local point-in-polygon: the client only ever
 * holds one office's boundary, and shipping all 125 to answer this would cost more than
 * the request does. `api.weather.gov` sends `Access-Control-Allow-Origin: *`, so this
 * works from the browser with no proxy.
 */
async function officeAt(latitude: number, longitude: number): Promise<Office | null> {
  const response = await fetch(
    `https://api.weather.gov/points/${latitude.toFixed(4)},${longitude.toFixed(4)}`,
    { headers: { Accept: "application/geo+json" }, signal: AbortSignal.timeout(15_000) },
  );
  if (!response.ok) return null;
  const properties = (await response.json())?.properties;
  const found = OFFICE_BY_ID.get(properties?.cwa as OfficeId);
  return found ?? null;
}

/**
 * Jump to the visitor's own forecast office.
 *
 * Deliberately **never prompts on page load**. An unbidden location prompt is a poor
 * trade for the reader and browsers increasingly penalise it, so the permission is only
 * ever requested from a real click. The one exception costs nothing: if permission was
 * *already* granted on a previous visit, the position is read silently — that returning
 * visitor has said yes, and re-asking would be the rude part.
 *
 * Silent location never overrides an explicit `?office=`, or a shared deep link would
 * quietly retarget itself at whoever opened it.
 */
function useLocalOffice(onSelect: (office: Office) => void) {
  const [state, setState] = useState<LocateState>("idle");
  const attempted = useRef(false);

  const apply = useCallback(async (position: GeolocationPosition) => {
    try {
      const found = await officeAt(position.coords.latitude, position.coords.longitude);
      // An office we can't draw is reported, not silently swapped for the default — the
      // same rule the ZIP/town search follows.
      if (!found?.ready) {
        setState("unavailable");
        return;
      }
      onSelect(found);
      setState("idle");
    } catch {
      setState("unavailable");
    }
  }, [onSelect]);

  const locate = useCallback(() => {
    if (!navigator.geolocation) {
      setState("unsupported");
      return;
    }
    setState("locating");
    navigator.geolocation.getCurrentPosition(
      (position) => void apply(position),
      (error) => setState(error.code === error.PERMISSION_DENIED ? "denied" : "unavailable"),
      { timeout: 12_000, maximumAge: 10 * 60 * 1000 },
    );
  }, [apply]);

  useEffect(() => {
    if (attempted.current) return;
    attempted.current = true;
    // Only for a visitor who has already granted it, and only when they have not asked
    // for a specific office.
    if (new URLSearchParams(window.location.search).has("office")) return;
    if (!navigator.geolocation || !navigator.permissions?.query) return;
    void navigator.permissions
      .query({ name: "geolocation" as PermissionName })
      .then((status) => {
        if (status.state === "granted") locate();
      })
      .catch(() => {});
  }, [locate]);

  return { state, locate };
}

function usePlaceIndex() {
  const [index, setIndex] = useState<PlaceIndex | null>(null);
  const [state, setState] = useState<IndexState>("idle");
  // Survives the menu unmounting between opens, so re-opening doesn't refetch.
  const started = useRef(false);

  const load = useCallback(() => {
    if (started.current) return;
    started.current = true;
    setState("loading");
    void (async () => {
      try {
        const response = await fetch("/place-index.json");
        if (!response.ok) throw new Error(`place index ${response.status}`);
        setIndex(parsePlaceIndex(await response.json()));
        setState("ready");
      } catch {
        // A failed load is recoverable: the next focus retries rather than leaving search
        // permanently dead for the session.
        started.current = false;
        setState("error");
      }
    })();
  }, []);

  return { index, state, load };
}

function OfficePicker({ office, onSelect }: { office: Office; onSelect: (office: Office) => void }) {
  const [open, setOpen] = useState(false);
  // The menu stays mounted through its exit animation, so "closing" is its own state.
  const [closing, setClosing] = useState(false);
  // The menu has two levels: the region list, and one region's offices. `openRegion` is
  // the region being browsed, or null for the region list. Region-first is what makes
  // this hold up at 122 offices — a flat list of every CWA in the country would not.
  const [openRegion, setOpenRegion] = useState<string | null>(null);
  // A non-empty query replaces whichever level is showing with its results — searching is
  // a third level, not a filter over the one you happen to be on.
  const [query, setQuery] = useState("");
  const container = useRef<HTMLDivElement>(null);
  const trigger = useRef<HTMLButtonElement>(null);
  const menu = useRef<HTMLDivElement>(null);
  const search = useRef<HTMLInputElement>(null);
  const exitTimer = useRef<number | null>(null);
  // The region last browsed, so backing out lands on the row you came from. Written only
  // from event handlers — the React Compiler forbids mutating it inside an effect.
  const lastRegion = useRef<string | null>(null);
  const region = findRegion(openRegion);
  const homeRegion = useMemo(() => regionOf(office.id), [office]);
  const places = usePlaceIndex();
  const local = useLocalOffice(onSelect);

  const searching = query.trim().length > 0;
  // An office found by search may not be drawable yet. It is still listed — telling
  // someone their town is forecast by GYX and that GYX isn't built is a real answer;
  // silently dropping it looks like their town doesn't exist.
  const results = useMemo(() => {
    if (!searching || !places.index) return [];
    return searchPlaces(places.index, query).flatMap((match) => {
      const found = OFFICE_BY_ID.get(match.office as OfficeId);
      return found ? [{ match, office: found }] : [];
    });
  }, [places.index, query, searching]);

  useEffect(() => () => { if (exitTimer.current) window.clearTimeout(exitTimer.current); }, []);

  const close = useCallback((restoreFocus: boolean) => {
    setClosing(true);
    if (exitTimer.current) window.clearTimeout(exitTimer.current);
    exitTimer.current = window.setTimeout(() => {
      setOpen(false);
      setClosing(false);
      // Reset to the region list so the menu always opens the same way.
      setOpenRegion(null);
      setQuery("");
    }, MENU_EXIT_MS);
    if (restoreFocus) trigger.current?.focus();
  }, []);

  const openMenu = useCallback(() => {
    if (exitTimer.current) window.clearTimeout(exitTimer.current);
    setClosing(false);
    setOpenRegion(null);
    setQuery("");
    lastRegion.current = null;
    setOpen(true);
  }, []);

  useEffect(() => {
    if (!open) return;
    const onPointerDown = (event: MouseEvent) => {
      if (!container.current?.contains(event.target as Node)) close(false);
    };
    document.addEventListener("mousedown", onPointerDown);
    return () => document.removeEventListener("mousedown", onPointerDown);
  }, [open, close]);

  // Every level change has to place focus, because changing level unmounts the row that
  // had it — focus would fall to <body>, and the key handler lives on the picker, so
  // Escape and the arrow keys would both stop working from there on.
  useEffect(() => {
    if (!open) return;
    // At 125 offices, typing a town is the fast path, so opening the menu lands in the
    // search box — except on a touch device, where focusing an input throws up the
    // on-screen keyboard over the very list it was meant to help you read.
    if (!openRegion && !window.matchMedia?.("(pointer: coarse)").matches) {
      search.current?.focus();
      return;
    }
    // Entering a region lands on its first office, where the eye already is; coming back
    // out lands on the region you were just in, rather than at the top of the list.
    const row = openRegion
      ? "button[data-office]"
      : `button[data-region="${lastRegion.current ?? REGIONS[0].id}"]`;
    menu.current?.querySelector<HTMLButtonElement>(row)?.focus();
  }, [open, openRegion]);

  const enterRegion = useCallback((id: string) => {
    lastRegion.current = id;
    setOpenRegion(id);
  }, []);

  const expanded = open && !closing;

  /** Walks focus through whatever rows the current level is showing. */
  const moveFocus = useCallback((step: number) => {
    const rows = [...(menu.current?.querySelectorAll<HTMLButtonElement>("button:not([disabled])") ?? [])];
    if (!rows.length) return;
    const index = rows.indexOf(document.activeElement as HTMLButtonElement);
    // Focus sitting in the search box is outside the list entirely (index -1), so the
    // list is entered from whichever end you were heading toward.
    if (index === -1) {
      rows[step > 0 ? 0 : rows.length - 1].focus();
      return;
    }
    rows[(index + step + rows.length) % rows.length].focus();
  }, []);

  const onKeyDown = useCallback((event: React.KeyboardEvent) => {
    if (event.key === "Escape") {
      event.preventDefault();
      // Escape unwinds one level at a time rather than throwing the whole menu away.
      if (expanded && searching) {
        setQuery("");
        search.current?.focus();
        return;
      }
      if (expanded && openRegion) {
        setOpenRegion(null);
        return;
      }
      close(true);
      return;
    }
    if (event.key === "ArrowDown" || event.key === "ArrowUp") {
      event.preventDefault();
      if (!expanded) {
        openMenu();
        return;
      }
      moveFocus(event.key === "ArrowDown" ? 1 : -1);
      return;
    }
    // Enter from the search box takes the first result you could actually go to, so a
    // ZIP can be typed and committed without ever leaving the keyboard.
    if (event.key === "Enter" && expanded && searching && event.target === search.current) {
      const first = results.find((entry) => entry.office.ready);
      if (!first) return;
      event.preventDefault();
      onSelect(first.office);
      close(true);
      return;
    }
    if (event.key === "ArrowLeft" && expanded && openRegion && event.target !== search.current) {
      event.preventDefault();
      setOpenRegion(null);
    }
  }, [close, expanded, moveFocus, onSelect, openMenu, openRegion, results, searching]);

  return (
    <div className={`office-picker${open ? " is-open" : ""}`} ref={container} onKeyDown={onKeyDown}>
      {/* Dims and blurs the page behind the free-standing pills. It sits inside the
          picker, so the outside-mousedown handler counts it as "inside" and won't fire —
          it closes the menu itself. Decorative and not focusable; Escape and a click on
          anything else still work. */}
      {open && (
        <div
          className={`office-scrim${closing ? " is-closing" : ""}`}
          aria-hidden="true"
          onMouseDown={() => close(false)}
        />
      )}
      <button
        ref={trigger}
        type="button"
        className="office-trigger"
        aria-haspopup="listbox"
        aria-expanded={expanded}
        aria-label={`Forecast office: ${office.label}. Change office`}
        onClick={() => (expanded ? close(false) : openMenu())}
      >
        <span className="brand-mark">{office.id}</span>
        <span className="office-trigger-text">
          <strong>Forecast Graphics</strong>
          <em>{office.label}</em>
        </span>
        <span className="office-caret" aria-hidden="true">▾</span>
      </button>
      {open && (
        <div className={`office-menu${closing ? " is-closing" : ""}`} ref={menu} tabIndex={-1}>
          {/* Outside the keyed group below, so changing level — or typing, which changes
              the level to "search" — never re-mounts the input and drops the caret. */}
          <div className="office-search">
            <span className="office-search-icon" aria-hidden="true">⌕</span>
            <input
              ref={search}
              type="search"
              value={query}
              role="combobox"
              aria-expanded={searching}
              aria-controls="office-search-results"
              aria-autocomplete="list"
              aria-label="Find a forecast office by town or ZIP code"
              placeholder="Town or ZIP code"
              autoComplete="off"
              spellCheck={false}
              onFocus={places.load}
              onChange={(event) => {
                places.load();
                setQuery(event.target.value);
              }}
            />
            {searching && (
              <button
                type="button"
                className="office-search-clear"
                aria-label="Clear search"
                onClick={() => {
                  setQuery("");
                  search.current?.focus();
                }}
              >
                ✕
              </button>
            )}
          </div>
          {/* Under the search box, because it answers the same question the search does —
              "which office is mine" — and is the one-tap version of it. */}
          <button
            type="button"
            className="office-locate"
            onClick={local.locate}
            disabled={local.state === "locating" || local.state === "unsupported"}
          >
            <b aria-hidden="true">◎</b>
            <span>
              {local.state === "locating" ? "Finding your forecast office…" : "Use my location"}
              {local.state === "denied" && <i>Location permission is blocked — search instead</i>}
              {local.state === "unavailable" && <i>Couldn’t find a forecast office for you</i>}
              {local.state === "unsupported" && <i>This browser can’t share a location</i>}
            </span>
          </button>
          {searching ? (
            <div
              className="office-group"
              key="search"
              id="office-search-results"
              // A listbox may only contain options, so the role goes on only when there
              // are results — the empty and loading states are status text, not a list.
              role={results.length ? "listbox" : undefined}
              aria-label={results.length ? "Search results" : undefined}
            >
              {places.state !== "ready" ? (
                <p className="office-status" role="status" style={{ "--row": 0 } as React.CSSProperties}>
                  {places.state === "error" ? "Search unavailable — check your connection." : "Loading places…"}
                </p>
              ) : !results.length ? (
                <p className="office-status" role="status" style={{ "--row": 0 } as React.CSSProperties}>
                  No town or ZIP matches “{query.trim()}”.
                </p>
              ) : (
                results.map(({ match, office: found }, index) => (
                  <button
                    key={`${match.kind}-${match.name}-${match.state}-${found.id}`}
                    type="button"
                    role="option"
                    aria-selected={found.id === office.id}
                    data-office={found.id}
                    // A town whose office isn't built yet is shown and named, but going
                    // there would draw a different office's map — so it is not selectable.
                    disabled={!found.ready}
                    className={`office-result${found.id === office.id ? " is-active" : ""}`}
                    style={{ "--row": index } as React.CSSProperties}
                    onClick={() => {
                      onSelect(found);
                      close(true);
                    }}
                  >
                    <b>{found.id}</b>
                    <span>
                      {match.kind === "zip" ? match.name : `${match.name}, ${match.state}`}
                      <i>{found.label}</i>
                    </span>
                    {!found.ready && <em>Soon</em>}
                  </button>
                ))
              )}
            </div>
          ) : region ? (
            <div className="office-group" key={region.id} role="listbox" aria-label={`${region.name} forecast offices`}>
              <button
                type="button"
                className="office-back"
                style={{ "--row": 0 } as React.CSSProperties}
                onClick={() => setOpenRegion(null)}
              >
                <b aria-hidden="true">←</b>
                <span>All NWS regions</span>
              </button>
              <p style={{ "--row": 1 } as React.CSSProperties}>{region.name}</p>
              {region.offices.map((entry, index) => (
                <button
                  key={entry.id}
                  type="button"
                  role="option"
                  aria-selected={entry.id === office.id}
                  data-office={entry.id}
                  // Listed but not selectable until its boundary, lattice and cities are
                  // built — picking it would draw another office's map, not fail visibly.
                  disabled={!entry.ready}
                  className={entry.id === office.id ? "is-active" : ""}
                  style={{ "--row": index + 2 } as React.CSSProperties}
                  onClick={() => {
                    onSelect(entry);
                    close(true);
                  }}
                >
                  <b>{entry.id}</b>
                  <span>{entry.city}, {entry.state}</span>
                  {!entry.ready && <em>Soon</em>}
                </button>
              ))}
            </div>
          ) : (
            <div className="office-group" key="regions" role="listbox" aria-label="Forecast region">
              <p style={{ "--row": 0 } as React.CSSProperties}>NWS Regions</p>
              {REGIONS.map((entry, index) => {
                const ready = entry.offices.filter((item) => item.ready).length;
                return (
                  <button
                    key={entry.id}
                    type="button"
                    data-region={entry.id}
                    // A region with nothing drawable yet is listed but not selectable:
                    // the map is the real one from the start, and what is missing is
                    // visibly missing rather than quietly absent.
                    disabled={!ready}
                    aria-current={entry.id === homeRegion.id ? "true" : undefined}
                    className={entry.id === homeRegion.id ? "is-current" : ""}
                    style={{ "--row": index + 1 } as React.CSSProperties}
                    onClick={() => enterRegion(entry.id)}
                  >
                    <b>{entry.short}</b>
                    <span>{entry.name}</span>
                    {/* No count. It read as "23 of 23" on almost every row once the
                        country was built out — noise that said nothing. A region with
                        nothing drawable is still marked, because that is the case where
                        the reader needs telling. */}
                    {!ready && <em>Soon</em>}
                  </button>
                );
              })}
              {/* Sits above the regions rather than inside one — it spans all of them. */}
              <button
                type="button"
                role="option"
                aria-selected={office.id === NATIONAL.id}
                className={`office-national${office.id === NATIONAL.id ? " is-active" : ""}`}
                data-region="national"
                data-office={NATIONAL.id}
                disabled={!NATIONAL.ready}
                style={{ "--row": REGIONS.length + 1 } as React.CSSProperties}
                onClick={() => {
                  onSelect(NATIONAL);
                  close(true);
                }}
              >
                <b aria-hidden="true">US</b>
                <span>National map</span>
                {!NATIONAL.ready && <em>Soon</em>}
              </button>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

export function ForecastGraphic() {
  const [forecast, setForecast] = useState<ForecastPayload | null>(null);
  const [publishedForecast, setPublishedForecast] = useState<PublishedForecastManifest | null>(null);
  const [bundle, setBundle] = useState<OfficeBundle | null>(null);
  const [outlooks, setOutlooks] = useState<OutlookPayloads>({ spc: null, wpc: null });
  // Distinct from "no outlook": tracks whether the outlook fetches have settled at all.
  const [outlookPending, setOutlookPending] = useState(true);
  const [dayIndex, setDayIndex] = useState(0);
  // Alerts are a view, not a fourth day: they describe what is in force right now, so they
  // sit alongside the day tabs rather than inside one. Kept as its own flag so `dayIndex`
  // stays a real day index everywhere else and nothing has to decode a sentinel value.
  const [showAlerts, setShowAlerts] = useState(false);
  // All three are stamped with the office they describe rather than cleared when it
  // changes. Clearing meant a synchronous setState at the top of the effect — which React
  // rightly objects to — and stamping also closes the window it was there to cover: a
  // stale payload can never be paired with the new office's zone geometry, because the
  // office has to match before either is read.
  const [zoneIndex, setZoneIndex] = useState<{ office: OfficeId; zones: ZoneIndex } | null>(null);
  const [alerts, setAlerts] = useState<{ office: OfficeId; payload: AlertPayload } | null>(null);
  const [alertsError, setAlertsError] = useState<OfficeId | null>(null);
  // Tracked separately per source. A single boolean could never be cleared correctly:
  // whichever loader succeeded last would wipe the other's failure, and the bundle loader
  // never cleared it at all — so one transient miss pinned the page on "temporarily
  // unavailable" until a hard reload, even once everything was fetching fine again.
  const [bundleError, setBundleError] = useState(false);
  const [forecastError, setForecastError] = useState(false);
  const error = bundleError || forecastError;

  // The server can't see the query string, so it renders the default office; the client
  // swaps to the requested one on hydration without a markup mismatch.
  const officeId = useSyncExternalStore(subscribeToOfficeParam, readOfficeParam, () => DEFAULT_OFFICE);
  const office = useMemo(() => findOffice(officeId), [officeId]);
  const selectOffice = useCallback((next: Office) => writeOfficeParam(next.id), []);

  // One bundle per office: its CWA outline, the counties/state lines/interstates inside
  // its frame, and the tile zoom that frame wants. The four national files this replaced
  // were clipped to the union of four offices' frames; at 125 they would have meant every
  // visitor downloading every county in the country to draw one map.
  useEffect(() => {
    let active = true;
    void (async () => {
      // Retried, because this effect only re-runs when the office changes: without it a
      // single transient miss — a deploy swapping the file, a dropped connection — would
      // strand the office until the visitor picked a different one and came back.
      for (let attempt = 0; active; attempt += 1) {
        try {
          const response = await fetch(`/offices/${office.id}.json`);
          if (!response.ok) throw new Error(`Office bundle ${response.status}`);
          const data = (await response.json()) as OfficeBundle;
          if (!active) return;
          setBundle(data);
          setBundleError(false);
          return;
        } catch {
          if (!active) return;
          if (attempt >= 2) {
            setBundleError(true);
            return;
          }
          await new Promise((done) => setTimeout(done, 500 * 2 ** attempt));
        }
      }
    })();
    return () => { active = false; };
  }, [office.id]);

  // Which office the loaded bundle is for, rather than clearing it on every change: a
  // bundle for the office we are no longer on must not be drawn, and this also covers a
  // slow fetch landing after the selection has already moved on again.
  const officeBundle = bundle?.office === office.id ? bundle : null;

  // One manifest covers every office, so it refreshes independently of the selection.
  // `manifestNonce` lets a failed image force an off-schedule refresh.
  const [manifestNonce, setManifestNonce] = useState(0);
  const lastManifestRecovery = useRef(0);

  // A broken published image almost always means the manifest is a publish behind and
  // the release it names has been pruned. Throttled so an asset that is genuinely gone
  // costs one refetch per 30s rather than a request per failed image.
  const recoverFromMissingAsset = useCallback(() => {
    const now = Date.now();
    if (now - lastManifestRecovery.current < 30_000) return;
    lastManifestRecovery.current = now;
    setManifestNonce((value) => value + 1);
  }, []);

  useEffect(() => {
    if (!PUBLISHED_ASSET_BASE_URL || !PUBLISHED_PLOTS_ENABLED) return;
    let active = true;
    const load = async () => {
      try {
        const response = await fetch(`/api/published-forecast?ts=${Date.now()}`, { cache: "no-store" });
        if (!response.ok) return;
        const manifest = await response.json() as PublishedForecastManifest;
        if (!active || (manifest.schemaVersion !== 1 && manifest.schemaVersion !== 2)) return;
        setPublishedForecast(manifest);
      } catch {
        // The live canvas path stays available when the manifest can't be read.
      }
    };
    void load();
    const refresh = window.setInterval(load, 15 * 60 * 1000);
    return () => { active = false; window.clearInterval(refresh); };
  }, [manifestNonce]);

  // The polygons alerts are drawn on. Fetched only once the alerts view is opened, and
  // only per office — ~180 KB that most visits never need, the same reason the place index
  // waits for the first search. Zone boundaries change on the order of years, so this is
  // never re-fetched on the alert refresh timer.
  useEffect(() => {
    if (!showAlerts || office.id === NATIONAL.id) return;
    let active = true;
    void (async () => {
      try {
        const response = await fetch(`/zones/${office.id}.json`);
        if (!response.ok) throw new Error(String(response.status));
        const bundle = await response.json() as { zones: ZoneIndex };
        if (active) setZoneIndex({ office: office.id, zones: bundle.zones });
      } catch {
        if (active) setAlertsError(office.id);
      }
    })();
    return () => { active = false; };
  }, [showAlerts, office.id]);

  const officeZones = zoneIndex?.office === office.id ? zoneIndex.zones : null;
  const officeAlerts = alerts?.office === office.id ? alerts.payload : null;

  // Active alerts. Refreshed far more often than anything else on the page: a warning's
  // lifetime is measured in tens of minutes, so the 15-minute manifest cadence would show
  // expired warnings and miss new ones for most of their duration.
  useEffect(() => {
    if (!showAlerts || !officeZones) return;
    let active = true;
    const codes = Object.keys(officeZones).join(",");
    const load = async () => {
      try {
        const response = await fetch(`/api/alerts?zones=${codes}`);
        if (!response.ok) throw new Error(String(response.status));
        const payload = await response.json() as AlertPayload;
        if (!active) return;
        setAlerts({ office: office.id, payload });
        setAlertsError(null);
      } catch {
        if (active) setAlertsError(office.id);
      }
    };
    void load();
    const refresh = window.setInterval(load, 2 * 60 * 1000);
    return () => { active = false; window.clearInterval(refresh); };
  }, [showAlerts, officeZones, office.id]);

  // SPC and WPC outlooks are national, so they load once and are shared by every office.
  // Only the live-canvas path needs them; published offices ship a baked PNG. The two
  // are independent: one centre being down leaves the other's products intact.
  useEffect(() => {
    let active = true;
    const fetchOutlook = async (path: string) => {
      const response = await fetch(path, { cache: "no-store", signal: AbortSignal.timeout(30_000) });
      if (!response.ok) throw new Error(`${path} ${response.status}`);
      return await response.json() as OutlookPayload;
    };
    const load = async () => {
      const [spc, wpc] = await Promise.allSettled([
        fetchOutlook("/api/spc-outlook"),
        fetchOutlook("/api/wpc-outlook"),
      ]);
      if (!active) return;
      // A failed centre keeps its previous payload rather than blanking products that
      // are still perfectly good; only the first load leaves it null, and that renders
      // an "unavailable" card rather than never resolving.
      setOutlooks((current) => ({
        spc: spc.status === "fulfilled" ? spc.value : current.spc,
        wpc: wpc.status === "fulfilled" ? wpc.value : current.wpc,
      }));
      setOutlookPending(false);
    };
    void load();
    const refresh = window.setInterval(load, 15 * 60 * 1000);
    return () => { active = false; window.clearInterval(refresh); };
  }, []);

  const publishedDays = publishedDaysFor(publishedForecast, office.id);
  const hasPublishedOffice = Boolean(publishedDays && publishedDays.length >= FORECAST_DAYS.length);

  // Only fetch live gridpoint data when this office has no published imagery to show.
  useEffect(() => {
    if (hasPublishedOffice) return;
    let active = true;
    const load = async () => {
      try {
        const payload = await loadForecast(office.id);
        if (!active) return;
        setForecast(payload);
        setForecastError(false);
      } catch {
        if (active) setForecastError(true);
      }
    };
    void load();
    const refresh = window.setInterval(load, 15 * 60 * 1000);
    return () => { active = false; window.clearInterval(refresh); };
  }, [office, hasPublishedOffice]);

  // The catalogue is day-aware: SPC issues split tornado/hail/wind probabilities only
  // through Day 2 and a combined severe probability only on Day 3, so those products
  // appear and disappear with the day tab rather than showing an empty map.
  const availableProducts = useMemo(() => PRODUCTS.filter((spec) => productDays(spec).includes(dayIndex + 1)), [dayIndex]);
  const availableGroups = useMemo(
    () => PRODUCT_GROUPS.filter((group) => availableProducts.some((product) => product.group === group.id)),
    [availableProducts],
  );
  const publishedDay = publishedDays?.[dayIndex];
  // Derived rather than cleared on switch, so a previous office's payload can never be
  // drawn against the newly selected office's boundary.
  const officeForecast = forecast?.office === office.id ? forecast : null;
  return (
    <main className="app-shell">
      <aside className="catalog-sidebar">
        <OfficePicker office={office} onSelect={selectOffice} />
        {/* The catalogue grew past one screen, which pushed the data-status footer off
            the bottom of the sidebar. Only the catalogue scrolls; the office picker and
            the status footer stay put, so "auto-updating" vs "published" is always
            visible no matter how far down the product list you are. */}
        <div className="catalog-scroll">
          <nav className="catalog-nav" aria-label="Forecast product catalogue">
            <p>Menu</p>
            <a className="is-active" href="#overview"><span>Overview</span><b>[{availableProducts.length}]</b></a>
            {availableGroups.map((group) => (
              <a key={group.id} href={`#product-${availableProducts.find((product) => product.group === group.id)!.id}`}>
                <span>{group.title}</span>
                <b>[{availableProducts.filter((product) => product.group === group.id).length}]</b>
              </a>
            ))}
          </nav>
          <div className="catalog-divider" />
          <nav className="product-index" aria-label="Individual forecast products">
            <p>Products</p>
            {availableProducts.map((spec) => <a key={spec.id} href={`#product-${spec.id}`}>{spec.nav}</a>)}
          </nav>
        </div>
        <footer className="catalog-footer">
          <span className="status-label">Data status</span>
          <span className="live-status"><i /> {hasPublishedOffice ? "PUBLISHED IMAGES" : "AUTO-UPDATING"}</span>
          <p>
            Source: National Weather Service<br />
            {/* The picker's trigger is a button, so the office link lives here instead. */}
            <a href={`https://www.weather.gov/${office.id.toLowerCase()}/`} target="_blank" rel="noreferrer">
              NWS {office.label} ↗
            </a>
          </p>
        </footer>
      </aside>

      <section className="catalog-workspace">
        <header className="workspace-topbar">
          <div className="breadcrumbs">
            <span>Forecast catalogue</span>
            <i>/</i>
            <nav className="day-switcher" aria-label="Forecast day">
              {/* Ahead of Day 1, because it is the only thing here describing right now
                  rather than a forecast day — and the first thing worth knowing. */}
              <button type="button" data-view="alerts" className={showAlerts ? "is-active" : ""} aria-pressed={showAlerts} onClick={() => setShowAlerts(true)}>
                Alerts
              </button>
              {FORECAST_DAYS.map((index) => (
                <button key={index} type="button" data-day-index={index} className={!showAlerts && dayIndex === index ? "is-active" : ""} aria-pressed={!showAlerts && dayIndex === index} onClick={() => { setShowAlerts(false); setDayIndex(index); }}>
                  Day {index + 1}
                </button>
              ))}
            </nav>
          </div>
          <a href="https://api.weather.gov/" target="_blank" rel="noreferrer">NWS data source ↗</a>
        </header>

        <div className="workspace-content" id="overview">
          <header className="catalog-heading">
            <h1>{showAlerts ? "Active Watches & Warnings" : `Day ${dayIndex + 1} Forecast Graphics`}</h1>
          </header>

          {showAlerts && (
            <AlertsPanel
              alerts={officeAlerts?.alerts ?? null}
              zones={officeZones}
              bundle={officeBundle}
              office={office}
              generatedAt={officeAlerts?.generatedAt ?? null}
              pending={!officeAlerts || !officeZones || !officeBundle}
              error={alertsError === office.id}
            />
          )}

          {!showAlerts && !hasPublishedOffice && !officeForecast && !error && <div className="gallery-message">Loading the latest NWS forecast plots…</div>}
          {!showAlerts && !hasPublishedOffice && error && <div className="gallery-message">Forecast data is temporarily unavailable.</div>}
          {!showAlerts && publishedDay && (
            <section className="forecast-gallery" aria-label={`Day ${dayIndex + 1} published forecast plots`} data-forecast-source="published" data-office={office.id}>
              {availableProducts.map((spec, index) => {
                const asset = publishedDay.products[spec.id];
                return asset ? <PublishedForecastPlot key={spec.id} spec={spec} asset={asset} dayIndex={dayIndex} eager={index === 0} office={office} onAssetMissing={recoverFromMissingAsset} /> : null;
              })}
            </section>
          )}
          {!showAlerts && !hasPublishedOffice && officeForecast && officeBundle && (
            <section className="forecast-gallery" aria-label={`Day ${dayIndex + 1} forecast plots`} data-office={office.id}>
              {availableProducts.map((spec) => (
                <ForecastPlot key={spec.id} spec={spec} forecast={officeForecast} outlook={spec.kind === "outlook" ? findOutlook(outlooks, spec, dayIndex + 1) : null} outlookPending={outlookPending} bundle={officeBundle} dayIndex={dayIndex} office={office} />
              ))}
            </section>
          )}
        </div>
      </section>
    </main>
  );
}
