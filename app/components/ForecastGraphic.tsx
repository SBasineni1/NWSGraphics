/**
 * The gridpoint forecast for one office.
 *
 * Prefers the copy the publisher precomputed into R2, because `/api/forecast` cannot serve
 * a live office on Cloudflare's free plan at all: it fans out to ~250 api.weather.gov
 * gridpoints, past both the 50-subrequest ceiling and the 10 ms CPU budget per invocation.
 * The publisher does that fan-out once an hour in Node, so the browser fetches one static
 * object instead — and NWS is hit once per publish rather than once per visitor.
 *
 * Falls back to the route because local development usually has no R2 configured, and
 * because an office added between publishes has no object yet.
 */
async function loadForecast(office: OfficeId): Promise<ForecastPayload> {
  if (PUBLISHED_ASSET_BASE_URL) {
    try {
      const response = await fetch(`/api/forecast-assets/forecast/${office}.json`);
      if (response.ok) return (await response.json()) as ForecastPayload;
    } catch {
      // Fall through to the live route rather than failing the render outright.
    }
  }
  const response = await fetch(`/api/forecast?office=${office}`, { cache: "no-store" });
  if (!response.ok) throw new Error("Forecast unavailable");
  return (await response.json()) as ForecastPayload;
}
